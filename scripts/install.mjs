#!/usr/bin/env node
// Writes one Luau script that installs this skill's Studio modules, for execute_luau.
//   node install.mjs [--out install.lua] [--only Cine|Capture]
// Installs (always as NEW ModuleScript instances, because require() in edit mode caches the old one):
//   templates/cine/Cine.lua    -> ReplicatedStorage.Cine
//   templates/cine/Capture.lua -> ReplicatedStorage.VFX.Capture  (same module and path as the VFX skill)
// Then read the output file and send its full text with execute_luau. It returns a one-line status.
import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const opt = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : undefined; };
const only = opt('--only');
const mods = [
  { name: 'Cine', file: join(here, '..', 'templates', 'cine', 'Cine.lua'), parent: 'game:GetService("ReplicatedStorage")' },
  { name: 'Capture', file: join(here, '..', 'templates', 'cine', 'Capture.lua'), parent: 'vfxFolder()' },
].filter((m) => !only || m.name === only);

function bracket(src) {
  for (let n = 4; n < 40; n++) { const close = ']' + '='.repeat(n) + ']'; if (!src.includes(close)) return ['[' + '='.repeat(n) + '[', close]; }
  throw new Error('no free long-bracket level');
}

const out = [
  '-- generated by scripts/install.mjs: installs the Cine skill modules as fresh instances',
  'local RS = game:GetService("ReplicatedStorage")',
  'local function vfxFolder()',
  '\tlocal f = RS:FindFirstChild("VFX")',
  '\tif not f then f = Instance.new("Folder"); f.Name = "VFX"; f.Parent = RS end',
  '\treturn f',
  'end',
  'local report = {}',
];
for (const m of mods) {
  const src = readFileSync(m.file, 'utf8');
  const [open, close] = bracket(src);
  out.push(
    'do',
    `\tlocal parent = ${m.parent}`,
    `\tlocal old = parent:FindFirstChild("${m.name}")`,
    '\tif old then old:Destroy() end',
    '\tlocal ms = Instance.new("ModuleScript")',
    `\tms.Name = "${m.name}"`,
    `\tms.Source = ${open}\n${src}${close}`,
    '\tms.Parent = parent',
    '\tlocal ok, res = pcall(require, ms)',
    `\ttable.insert(report, ok and ("${m.name} ok at " .. ms:GetFullName()) or ("${m.name} FAILED: " .. tostring(res)))`,
    'end',
  );
}
out.push('return table.concat(report, "; ")');
const text = out.join('\n') + '\n';
const file = opt('--out');
if (file) { writeFileSync(file, text); console.log(`wrote ${file} (${text.length} bytes): send its whole text with execute_luau`); }
else process.stdout.write(text);
