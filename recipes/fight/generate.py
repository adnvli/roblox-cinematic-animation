LF=[-0.55,-2.88,0.5]; RF=[0.6,-2.88,-0.45]
def G(dz=0.0):
    return {"Root":{"position":[0,-0.15,dz],"rotation":[0,-16,0]},"Waist":{"rotation":[-4,-6,0]},"Neck":{"rotation":[-6,10,0]},
      "LeftHip":{"aimAt":[LF[0],LF[1],LF[2]+(-dz)]},"RightHip":{"aimAt":[RF[0],RF[1],RF[2]+(-dz)]},
      "LeftShoulder":{"aim":[-0.1,-0.45,0.9]},"LeftElbow":{"bend":100},"RightShoulder":{"aim":[0.3,-0.8,0.5]},"RightElbow":{"bend":130}}
def R(pos,rot): return {"Root":{"position":pos,"rotation":rot}}
def W(x,y,z=0): return {"Waist":{"rotation":[x,y,z]}}
def N(x,y,z=0): return {"Neck":{"rotation":[x,y,z]}}
def LA(aim,bend,bt=None):
    d={"LeftShoulder":{"aim":aim},"LeftElbow":{"bend":bend}}
    if bt: d["LeftShoulder"]["bendToward"]=bt
    return d
def RA(aim,bend,bt=None):
    d={"RightShoulder":{"aim":aim},"RightElbow":{"bend":bend}}
    if bt: d["RightShoulder"]["bendToward"]=bt
    return d
def feet(l,r): return {"LeftHip":{"aimAt":l},"RightHip":{"aimAt":r}}
def K(t,*parts,name=None,markers=None):
    j={}
    for p in parts: j.update(copy.deepcopy(p))
    k={"time":t,"joints":j}
    if name: k["name"]=name
    if markers: k["markers"]=[{"name":m} for m in markers]
    return k
def save(name,keys,prio="Action",loop=False):
    json.dump({"name":name,"rig":"R15","priority":prio,"loop":loop,"keyframes":keys},open(name+".json","w"),indent=1)

